"""Generate native Android resources from the explicitly reviewed UI translation catalogue."""
from pathlib import Path
import re, json, hashlib, html
ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'app/src/main/java/com/ling/iwaraflow'
CAT = ROOT / 'tools/ui_translations.tsv'

def strings(source):
    i = 0
    while i < len(source):
        if source.startswith('//', i):
            i = source.find('\n', i)
            if i < 0: return
        elif source.startswith('/*', i):
            end = source.find('*/', i + 2); i = len(source) if end < 0 else end + 2
        elif source[i] == "'":
            i += 1
            while i < len(source):
                if source[i] == '\\': i += 2
                elif source[i] == "'": i += 1; break
                else: i += 1
        elif source.startswith('"""', i):
            end = source.find('"""', i + 3); i = len(source) if end < 0 else end + 3
        elif source[i] == '"':
            start = i; i += 1; literal = ''; args = []
            while i < len(source):
                c = source[i]
                if c == '\\': literal += source[i:i+2]; i += 2
                elif c == '"':
                    i += 1
                    try: text = json.loads('"' + literal.replace("\\'", "'").replace('\\$', '$') + '"')
                    except ValueError: break
                    yield start, i, text, args
                    break
                elif c == '$' and i + 1 < len(source) and source[i+1] == '{':
                    pos = i + 2; depth = 1; i = pos
                    while i < len(source) and depth:
                        if source[i] == '"':
                            i += 1
                            while i < len(source):
                                if source[i] == '\\': i += 2
                                elif source[i] == '"': i += 1; break
                                else: i += 1
                        elif source[i] == '{': depth += 1; i += 1
                        elif source[i] == '}': depth -= 1; i += 1
                        else: i += 1
                    args.append(source[pos:i-1]); literal += f'%{len(args)}$s'
                elif c == '$' and i + 1 < len(source) and (source[i+1].isalpha() or source[i+1] == '_'):
                    m = re.match(r'\$(\w+)', source[i:]); args.append(m.group(1)); i += len(m.group())
                    literal += f'%{len(args)}$s'
                else: literal += c; i += 1
        else: i += 1

def ui_files():
    return [p for p in SRC.glob('*.kt') if any(x in p.stem for x in
        ['Activity', 'Adapter', 'Panel', 'Dialog', 'Sheet', 'View', 'Guide', 'Page', 'Menu',
         'Share', 'Ui', 'Update', 'PermissionPrompt', 'ClipboardLink', 'ErrorMessage',
         'DanmakuSettings', 'PlaylistPicker', 'PlaylistManagement', 'InterestManager', 'SearchSort', 'AuthorFollowButton',
         'Translator', 'RecommendationCandidate', 'RecommendationRanker', 'StartupNetworkHelp', 'NetworkQualityHint', 'EndOfFeedHint']) and p.stem != 'UiText']

def candidates():
    out = {}
    for p in ui_files():
        source = p.read_text(encoding='utf-8')
        for start, end, text, args in strings(source):
            line = source[source.rfind('\n', 0, start)+1:start]
            if re.search('[\u4e00-\u9fff]', text) and 'const val' not in line:
                out.setdefault(text, []).append(p.name)
    for p in (ROOT/'app/src/main/res/layout').glob('*.xml'):
        for value in re.findall(r'android:(?:text|hint|contentDescription)="([^"]+)"', p.read_text(encoding='utf-8')):
            text = html.unescape(value).replace('\\n', '\n')
            if re.search('[\u4e00-\u9fff]', text): out.setdefault(text, []).append(p.name)
    return out

def escaped(text): return text.replace('\\', '\\\\').replace('\n', '\\n').replace('\t', '\\t')
def unescaped(text): return text.replace('\\u0020', ' ').replace('\\n', '\n').replace('\\t', '\t').replace('\\\\', '\\')
def key(text): return 'ui_' + hashlib.sha256(text.encode()).hexdigest()[:12]
def kotlin(text): return json.dumps(text, ensure_ascii=False).replace('$', '\\$')

def generate():
    rows = {}
    for line in CAT.read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'): continue
        cells = line.split('\t'); assert len(cells) == 4, line
        cells = [unescaped(x) for x in cells]; assert cells[0] not in rows, cells[0]
        rows[cells[0]] = cells
        placeholders = sorted(re.findall(r'%\d+\$s', cells[0]))
        for target in cells[1:]: assert sorted(re.findall(r'%\d+\$s', target)) == placeholders, cells
    for index, locale in enumerate(['values', 'values-en', 'values-ja', 'values-ko']):
        lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/localize_ui.py; edit tools/ui_translations.tsv. -->', '<resources>']
        for original, row in rows.items():
            value = html.escape(row[index], quote=False).replace('\\', '\\\\').replace('"', '\\"').replace("'", "\\'").replace('\n', '\\n')
            lines.append(f'    <string name="{key(original)}" formatted="false">"{value}"</string>')
        lines.append('</resources>')
        path = ROOT/'app/src/main/res'/locale/'ui_strings.xml'; path.parent.mkdir(exist_ok=True)
        path.write_text('\n'.join(lines)+'\n', encoding='utf-8')
    for p in ui_files():
        source = p.read_text(encoding='utf-8'); changes = []
        for start, end, text, args in strings(source):
            line = source[source.rfind('\n', 0, start)+1:start]
            whole_line = source[source.rfind('\n', 0, start)+1:source.find('\n', end) if source.find('\n', end) >= 0 else len(source)]
            if text not in rows or 'const val' in line or '// ui-literal' in whole_line or re.search(r'UiText\.text\(R\.string\.\w+,\s*$', line): continue
            values = ''.join(', ' + arg for arg in args)
            changes.append((start, end, f'UiText.text(R.string.{key(text)}, {kotlin(text)}{values})'))
        for start, end, replacement in reversed(changes): source = source[:start] + replacement + source[end:]
        if changes: p.write_text(source, encoding='utf-8')
    for p in (ROOT/'app/src/main/res/layout').glob('*.xml'):
        def replace(m):
            text = html.unescape(m.group(2)).replace('\\n', '\n')
            return f'android:{m.group(1)}="@string/{key(text)}"' if text in rows else m.group()
        source = p.read_text(encoding='utf-8')
        changed = re.sub(r'android:(text|hint|contentDescription)="([^"]+)"', replace, source)
        if source != changed: p.write_text(changed, encoding='utf-8')

if __name__ == '__main__':
    import sys
    if '--generate' in sys.argv: generate()
    else:
        for text, files in sorted(candidates().items(), key=lambda pair:(len(pair[0]),pair[0])):
            print(escaped(text) + '\t' + ','.join(sorted(set(files))))
